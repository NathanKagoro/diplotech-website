// Generates public/globe.svg: an orthographic globe with a 15 degree
// graticule and rough continent outlines, in thin ink lines.
// Run with `npm run map` after changing the centre or the outlines.
import { writeFileSync } from 'node:fs'
import { project, clampToLimb, densify, visibleRuns, toPath } from './lib/projection.mjs'
import { LAND } from './land.mjs'

const R = 300
const view = { lon0: 22, lat0: 14, r: R }
const P = ([lon, lat]) => project(lon, lat, view)

// Graticule: meridians and parallels every 15 degrees.
const lines = []
for (let lon = -180; lon < 180; lon += 15) {
  lines.push(densify([[lon, -82.5], [lon, 82.5]], 4))
}
for (let lat = -75; lat <= 75; lat += 15) {
  const ring = []
  for (let lon = -180; lon <= 180; lon += 4) ring.push([lon, lat])
  lines.push(ring)
}
const graticule = lines
  .flatMap((line) => visibleRuns(line.map(P)))
  .map((run) => toPath(run))
  .join('')

let coast = ''
let land = ''
for (const outline of Object.values(LAND)) {
  const pts = densify(outline, 2, true).map(P)
  if (!pts.some((p) => p.visible)) continue
  // Fill: far-side points slide to the limb so the shape closes along the edge.
  land += toPath(pts.map((p) => (p.visible ? p : clampToLimb(p, R))), true)
  // Stroke: only the near-side runs, so no ink is drawn along the limb.
  if (pts.every((p) => p.visible)) coast += toPath(pts, true)
  else {
    // Rotate so the walk starts on the far side, then runs do not wrap.
    const start = pts.findIndex((p) => !p.visible)
    const rotated = [...pts.slice(start), ...pts.slice(0, start + 1)]
    coast += visibleRuns(rotated).map((run) => toPath(run)).join('')
  }
}

// Tick marks round the limb every 5 degrees of bearing, longer every 15.
let ticks = ''
for (let a = 0; a < 360; a += 5) {
  const t = (a * Math.PI) / 180
  const len = a % 15 === 0 ? 10 : 5
  const p1 = { x: Math.sin(t) * (R + 4), y: -Math.cos(t) * (R + 4) }
  const p2 = { x: Math.sin(t) * (R + 4 + len), y: -Math.cos(t) * (R + 4 + len) }
  ticks += toPath([p1, p2])
}

const PAD = 22
const size = (R + PAD) * 2
const INK = '#0b5b70'
const out = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${-R - PAD} ${-R - PAD} ${size} ${size}" width="${size}" height="${size}">
<!-- Generated by scripts/make-map.mjs. Centre ${view.lat0}N ${view.lon0}E. Do not edit by hand. -->
<path d="${land}" fill="${INK}" fill-opacity=".11"/>
<g fill="none" stroke="${INK}" stroke-linejoin="round">
<path d="${graticule}" stroke-width=".6" opacity=".45"/>
<path d="${coast}" stroke-width="1.3"/>
<circle r="${R}" stroke-width="1.3"/>
<path d="${ticks}" stroke-width=".8"/>
</g>
</svg>
`
writeFileSync(new URL('../public/globe.svg', import.meta.url), out)
console.log(`public/globe.svg written, ${(out.length / 1024).toFixed(1)} KB, ${size} x ${size}`)
